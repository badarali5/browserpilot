ExecutionResult = Dict[str, Any]


def validate_target_url(target_url: str, allowed_origins: Optional[List[str]] = None) -> str:
    """Validate a target origin against the configured local demo allowlist."""
    if not isinstance(target_url, str) or not target_url.strip():
        raise ValueError("A target URL is required.")

    parsed = urlparse(target_url.strip())
    if parsed.scheme not in {"http", "https"}:
        raise ValueError("Target URL must use http or https.")
    if parsed.username or parsed.password or parsed.query or parsed.fragment:
        raise ValueError("Target URL must not contain credentials, query parameters, or fragments.")
    if not parsed.hostname:
        raise ValueError("Target URL must include a hostname.")

    origin = f"{parsed.scheme}://{parsed.netloc}"
    configured = allowed_origins
    if configured is None:
        raw_allowed = os.getenv(
            "BROWSERPILOT_ALLOWED_ORIGINS",
            "http://127.0.0.1:8000,http://localhost:8000",
        )
        configured = [item.strip().rstrip("/") for item in raw_allowed.split(",") if item.strip()]

    if origin not in configured:
        raise ValueError(
            "Target URL is not in the configured allowlist. "
            "Set BROWSERPILOT_ALLOWED_ORIGINS for authorized origins."
        )

    hostname = parsed.hostname
    try:
        ip_addresses = [ipaddress.ip_address(hostname)]
    except ValueError:
        try:
            ip_addresses = [
                ipaddress.ip_address(address[4][0])
                for address in socket.getaddrinfo(hostname, None)
            ]
        except socket.gaierror as exc:
            raise ValueError("Target hostname could not be resolved.") from exc

    is_loopback_origin = (
        hostname in {"127.0.0.1", "localhost"}
        and origin in configured
    )
    for address in ip_addresses:
        if not is_loopback_origin and (
            address.is_private
            or address.is_loopback
            or address.is_link_local
            or address.is_reserved
            or address.is_multicast
        ):
            raise ValueError("Internal and non-public target addresses are not allowed.")
    return origin


def resolve_navigation_url(target_url: str, url: Optional[str]) -> str:
    if not isinstance(url, str) or not url.strip():
        raise ValueError("Navigate action requires a non-empty URL.")

    target_origin = urlparse(target_url)
    resolved = urljoin(target_url.rstrip("/") + "/", url.strip())
    resolved_origin = urlparse(resolved)
    if (
        resolved_origin.scheme not in {"http", "https"}
        or resolved_origin.scheme != target_origin.scheme
        or resolved_origin.netloc != target_origin.netloc
    ):
        raise ValueError("Navigation URL must stay on the configured target origin.")
    return resolved


def make_result(step_num: int, action: str, status: str, evidence: str = "", error: str = "") -> ExecutionResult:
    """Create a standardized execution result dict."""
    return {
        "step": step_num,
        "action": action,
        "status": status,  # "pass", "fail", "error", "timeout"
        "evidence": evidence,
        "error": error,
    }


# ══════════════════════════════════════
# Core: Execute Single Step
# ══════════════════════════════════════

async def execute_step(
    page,
    step: Dict[str, Any],
    timeout: int = 10,
) -> ExecutionResult:
    """Execute a single test step against the current page.

    Args:
        page: Playwright page object
        step: Step dict from the test plan
        timeout: Maximum wait time in seconds

    Returns:
        Execution result dict
    """
    action = step.get("action")
    selector = step.get("selector")
    value = step.get("value")
    expected = step.get("expected")

    result: ExecutionResult = make_result(step_num=0, action=action, status="error")
    observation_before = None
    if action in {"navigate", "input", "click", "assert"}:
        try:
            observation_before = await capture_page_snapshot(page)
            result["observation_before"] = observation_before
        except Exception:
            result["observation_before"] = None

    try:
        if action == "navigate":
            url = step.get("url") or value or "/"
            await page.goto(url, wait_until="domcontentloaded", timeout=timeout * 1000)
            result = make_result(
                step_num=step.get("step", 1),
                action="navigate",
                status="pass",
                evidence=f"Navigated to {url}; page title: {await page.title()}",
            )

        elif action == "input":
            if not selector or value is None:
                return make_result(
                    step_num=step.get("step", 1),
                    action="input",
                    status="error",
                    evidence="Input step missing selector or value",
                    error="Missing selector or value",
                )

            element = await page.wait_for_selector(selector, timeout=timeout * 1000)
            if element:
                await element.fill(value)
                await element.press("Tab")  # Move focus
                if selector and "password" in selector.lower():
                    evidence_value = "[redacted]"
                else:
                    evidence_value = str(value)
                result = make_result(
                    step_num=step.get("step", 1),
                    action="input",
                    status="pass",
                    evidence=f"Entered '{evidence_value}' into {selector}",
                )
            else:
                return make_result(
                    step_num=step.get("step", 1),
                    action="input",
                    status="fail",
                    evidence=f"Element not found: {selector}",
                    error=f"Selector '{selector}' not found on page",
                )

        elif action == "click":
            if not selector:
                return make_result(
                    step_num=step.get("step", 1),
                    action="click",
                    status="error",
                    evidence="Click step missing selector",
                    error="Missing selector",
                )
            if selector.startswith("text="):
                element = page.get_by_text(selector[5:], exact=False)
                await element.first.click(timeout=timeout * 1000)
                result = make_result(
                    step_num=step.get("step", 1),
                    action="click",
                    status="pass",
                    evidence=f"Clicked element: {selector}",
                )
            else:
                element = await page.wait_for_selector(selector, timeout=timeout * 1000)
                if element:
                    await element.click()
                    result = make_result(
                        step_num=step.get("step", 1),
                        action="click",
                        status="pass",
                        evidence=f"Clicked element: {selector}",
                    )
                else:
                    return make_result(
                        step_num=step.get("step", 1),
                        action="click",
                        status="fail",
                        evidence=f"Element not found: {selector}",
                        error=f"Selector '{selector}' not found",
                    )

        elif action == "assert":
            if not expected:
                return make_result(
                    step_num=step.get("step", 1),
                    action="assert",
                    status="error",
                    evidence="Assert step missing expected value",
                    error="Missing expected value",
                )
            verification_step = {**step, "condition": step.get("condition") or "text_present"}
            verification = await verify(page, verification_step, timeout=timeout)
            result = make_result(
                step_num=step.get("step", 1),
                action="assert",
                status=verification["status"],
                evidence=verification["details"] or f"Condition '{verification['condition']}' checked",
                error=verification["error"],
            )
            result["verification"] = verification
        elif action == "screenshot":
            filepath = step.get("filepath") or value or f"screenshot_step_{step.get('step', 1)}.png"
            screenshot_root = step.get("_artifact_dir")
            if screenshot_root:
                filepath = str(Path(screenshot_root) / Path(filepath).name)
            await page.screenshot(path=filepath)
            result = make_result(
                step_num=step.get("step", 1),
                action="screenshot",
                status="pass",
                evidence=f"Screenshot saved to {filepath}",
            )

        else:
            result = make_result(
                step_num=step.get("step", 1),
                action=action,
                status="error",
                evidence=f"Unknown action: {action}",
                error=f"Unsupported action: {action}",
            )

    except PlaywrightTimeoutError:
        result = make_result(
            step_num=step.get("step", 1),
            action=action,
            status="timeout",
            evidence=f"Timeout ({timeout}s) performing {action}",
            error=f"Playwright timeout on action: {action}",
        )
    except Exception as e:
        result = make_result(
            step_num=step.get("step", 1),
            action=action,
            status="error",
            evidence="",
            error=str(e),
        )

    if observation_before is not None:
        result["observation_before"] = observation_before
    if action in {"navigate", "input", "click", "assert", "screenshot"}:
        try:
            result["observation_after"] = await capture_page_snapshot(page)
        except Exception as exc:
            result["observation_after"] = None
            if result["status"] == "pass":
                result["status"] = "error"
                result["error"] = f"Could not capture post-action observation: {exc}"

    return result


# ══════════════════════════════════════
# Core: Execute Full Plan
# ══════════════════════════════════════

async def execute_plan(
    plan: Dict[str, Any],
    headless: bool = True,
    timeout: int = 30,
    target_url: str = "http://127.0.0.1:8000",
    screenshot_dir: str = "reports",
) -> Dict[str, Any]:
    """Execute a complete test plan using Playwright.

    Args:
        plan: Test plan dict from the AI planner
        headless: Whether to run browser headless (no UI)
        timeout: Maximum total execution time in seconds

    Returns:
        Execution report dict with results, summary, and evidence
    """
    target_url = validate_target_url(target_url)
    plan_id = plan.get("plan_id", f"plan_{int(time.time())}")
    steps = plan.get("steps", [])
    goal = plan.get("goal", "")

    report: ExecutionResult = {
        "plan_id": plan_id,
        "goal": goal,
        "steps": [],
        "summary": {
            "total_steps": len(steps),
            "passed": 0,
            "failed": 0,
            "errors": 0,
            "timeouts": 0,
            "success_rate": 0.0,
        },
        "screenshots": [],
        "bugs_detected": plan.get("bugs_detected", []),
        "execution_time": 0.0,
        "console_errors": [],
        "failed_network_requests": [],
        "http_responses": [],
        "trace_path": None,
        "current_url": target_url,
        "evidence_errors": [],
    }

    start_time = time.time()
    artifact_dir = Path(screenshot_dir)
    artifact_dir.mkdir(parents=True, exist_ok=True)
    target_origin = f"{urlparse(target_url).scheme}://{urlparse(target_url).netloc}"

    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=headless)
        context = await browser.new_context(base_url=target_url)
        page = await context.new_page()

        try:
            await context.tracing.start(screenshots=True, snapshots=True, sources=True)
        except Exception as exc:
            report["evidence_errors"].append(f"Trace collection failed: {exc}")

        def record_console(message):
            if message.type == "error":
                report["console_errors"].append(str(message.text))

        def record_failed_request(request):
            report["failed_network_requests"].append({
                "url": request.url,
                "method": request.method,
                "failure": request.failure,
            })

        def record_response(response):
            if response.request.resource_type in {"document", "xhr", "fetch"}:
                report["http_responses"].append({
                    "url": response.url,
                    "status": response.status,
                    "status_text": response.status_text,
                    "resource_type": response.request.resource_type,
                })

        page.on("console", record_console)
        page.on("requestfailed", record_failed_request)
        page.on("response", record_response)

        try:
            for i, step in enumerate(steps, 1):
                # Mark step number in the step dict
                step_with_num = {**step, "step": i}
                if step_with_num.get("action") == "navigate":
                    url = step_with_num.get("url")
                    step_with_num["url"] = resolve_navigation_url(target_url, url)
                elif step_with_num.get("action") == "screenshot":
                    step_with_num["_artifact_dir"] = str(artifact_dir)

                # Execute the step
                result = await execute_step(page, step_with_num, timeout=timeout)

                # Add step to report
                report["steps"].append(result)

                # Update summary
                if result["status"] == "pass":
                    report["summary"]["passed"] += 1
                elif result["status"] == "fail":
                    report["summary"]["failed"] += 1
                elif result["status"] == "error":
                    report["summary"]["errors"] += 1
                elif result["status"] == "timeout":
                    report["summary"]["timeouts"] += 1

                # Capture screenshot after each step (optional)
                try:
                    ss_path = str(artifact_dir / f"ss_{plan_id}_step_{i}.png")
                    await page.screenshot(path=ss_path)
                    report["screenshots"].append(ss_path)
                except Exception as exc:
                    report["evidence_errors"].append(f"Screenshot collection failed for step {i}: {exc}")

        finally:
            report["current_url"] = page.url
            trace_path = artifact_dir / f"trace_{plan_id}.zip"
            try:
                await context.tracing.stop(path=str(trace_path))
                report["trace_path"] = str(trace_path)
            except Exception as exc:
                report["evidence_errors"].append(f"Trace collection failed: {exc}")
            await context.close()
            await browser.close()

    # Calculate final summary
    total = report["summary"]["total_steps"]
    passed = report["summary"]["passed"]
    report["summary"]["success_rate"] = round((passed / total) * 100, 1) if total > 0 else 0.0
    report["execution_time"] = round(time.time() - start_time, 2)

    return report


